import { writeFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import type { AircraftId } from '../src/aircraft';
import { flightTest, passes, reportTable, TOLERANCE, withinTolerance, type FlightTestRow } from './flightTest/programme';

// Stage 8 automated test pilot: flies all three aircraft through the CLAUDE.md test
// points, prints the results table and writes it to docs/FLIGHT_TEST_REPORT.md.
// Run on its own with `npm run flight-test`.

const REPORT = new URL('../docs/FLIGHT_TEST_REPORT.md', import.meta.url);
const ORDER: AircraftId[] = ['airbike103', 'decathlon8kcab', 'bensenB8M'];

describe('flight test programme (CLAUDE.md targets, ±10 %)', () => {
  const rows: FlightTestRow[] = [];

  for (const id of ORDER) {
    it(`flies the ${id} test points`, () => {
      const r = flightTest(id);
      rows.push(...r);
      for (const row of r) {
        expect(Number.isNaN(row.measured), `${row.aircraft} ${row.test} did not complete`).toBe(false);
        expect(passes(row), `${row.aircraft} ${row.test}: ${row.measured.toFixed(1)} vs ${row.target} ${row.unit}`).toBe(true);
      }
    }, 600_000);
  }

  it('writes the report', () => {
    const table = reportTable(rows);
    const failed = rows.filter((r) => !passes(r)).length;
    const accepted = rows.filter((r) => passes(r) && !withinTolerance(r)).length;
    const text = [
      '# Flight test report',
      '',
      'Generated by the automated test pilot (`npm run flight-test`, tests/flightTest/programme.ts).',
      `Conditions: ISA, calm air, field elevation 50 ft, pilot 90 kg, full fuel. Pass = within ±${TOLERANCE * 100} % of CLAUDE.md.`,
      'Speeds are indicated unless marked TAS. "info" rows have no CLAUDE.md target and are measured for reference.',
      '',
      table,
      '',
      `${rows.length} test points: ${failed === 0 ? 'all pass' : `${failed} FAIL`}${accepted ? ` (${accepted} accepted deviation${accepted > 1 ? 's' : ''})` : ''}.`,
      '',
    ].join('\n');
    writeFileSync(REPORT, text);
    console.info(`\n${table}\n`);
    expect(rows.length).toBeGreaterThan(0);
  });
});
